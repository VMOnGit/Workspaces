module rom_16x4(
    output reg [15:0] q,
    input wire [3:0] addr,
    input wire clk
);


always@(posedge clk) begin
    case(addr)
        4'b0000: q <= 16'b1010_1010_1010_1010;
        4'b0001: q <= 16'b0111_0111_0111_0110;
        4'b0010: q <= 16'b1111_0000_1111_0000;
        4'b0011: q <= 16'b1000_1000_1000_1000;
        4'b0100: q <= 16'b0100_0100_0001_0001;
        4'b0101: q <= 16'b0011_0011_0011_0011;
        4'b0110: q <= 16'b1001_1001_1001_1001;
        4'b0111: q <= 16'b1000_0001_1000_0001;
        4'b1000: q <= 16'b0011_0101_0011_0101;
        4'b1001: q <= 16'b0010_0010_0010_0010;
        4'b1010: q <= 16'b0110_0110_1001_1001;
        4'b1011: q <= 16'b0000_1000_0000_1010;
        4'b1100: q <= 16'b0001_1100_0000_0101;
        4'b1101: q <= 16'b0010_1010_0000_1010;
        4'b1110: q <= 16'b0100_1001_0000_0101;
        4'b1111: q <= 16'b1000_1111_0000_1010;
        default: q <= 16'b0001_0000_0000_0101;
    endcase
end


endmodule